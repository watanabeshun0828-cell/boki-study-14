async function saved(page: Page) { await expect(page.getByText('この端末に保存済み', {exact:true})).toBeVisible() }
async function nav(page: Page, id: string) { await page.goto('#/' + id); await saved(page) }
async function start(page: Page, day = 3) {
  await page.goto('./#/quiz')
  await page.getByLabel('練習する日').selectOption(String(day))
  await page.getByRole('button', { name: '練習をはじめる', exact: true }).click()
}
async function fillJournal(page: Page, entries: {side:string;accountId:string;amount:number}[]) {
  for (const side of ['debit','credit']) {
    const rows = entries.filter(e => e.side === side).reverse()
    const label = side === 'debit' ? '借方' : '貸方'
    for(let i=0;i<rows.length;i++) {
      if(i) await page.getByRole('button',{name: label + 'の行を追加',exact:true}).click()
      await page.getByLabel(label + ' 科目' + (i+1),{exact:true}).selectOption(rows[i].accountId)
      await page.getByLabel(label + ' 金額' + (i+1),{exact:true}).fill(String(rows[i].amount))
    }
  }
}
