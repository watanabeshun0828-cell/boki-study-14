test('Service Workerの更新後もメモと途中回答を引き継ぐ', async ({ page }) => {
  await page.goto('./#/lessons')
  await page.getByRole('textbox',{name:'自分の言葉でメモ'}).fill('更新でも残す学習メモ')
  await saved(page)
  await start(page)
  await page.getByLabel('借方 科目1',{exact:true}).selectOption('cash')
  await page.getByLabel('借方 金額1',{exact:true}).fill('20000')
  await saved(page)
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload()
  await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true)
  const indexPath=path.resolve('dist/index.html'),swPath=path.resolve('dist/sw.js')
  const [index,sw]=await Promise.all([readFile(indexPath,'utf8'),readFile(swPath,'utf8')])
  const updated=index+'\n<!-- local update preservation verification -->\n'
  const revision=createHash('md5').update(updated).digest('hex')
  const updatedSW=sw.replace(/(url:"index\.html",revision:")[^"]+"/, '$1'+revision+'"')
  expect(updatedSW).not.toBe(sw)
  try {
    await writeFile(indexPath,updated)
    await writeFile(swPath,updatedSW)
    await page.evaluate(async()=>{const r=await navigator.serviceWorker.getRegistration();await r?.update()})
    await expect(page.getByRole('button',{name:'保存して更新'})).toBeVisible()
    await page.getByRole('button',{name:'保存して更新'}).click()
    await expect(page.getByRole('button',{name:'保存して更新'})).not.toBeVisible()
    await expect(page.getByLabel('借方 金額1',{exact:true})).toHaveValue('20000')
    await nav(page,'lessons')
    await page.getByLabel('学習する日').selectOption('1')
    await expect(page.getByRole('textbox',{name:'自分の言葉でメモ'})).toHaveValue('更新でも残す学習メモ')
  } finally { await writeFile(indexPath,index);await writeFile(swPath,sw) }
})

